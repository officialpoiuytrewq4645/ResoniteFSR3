# Copies the FSR 3.1 Upscaler shaders from upstream FSR3Unity into the Unity 2019.4 shader project and
# adapts them for Unity 2019:
#   1. cbuffers -> one-element StructuredBuffers (Unity 2019 has no CommandBuffer.SetComputeConstantBufferParam)
#   2. multi_compile keywords -> fixed #defines, one .compute file per needed variant
#      (Unity 2019 does not support multi_compile in compute shaders)
param(
    [string]$UpstreamShaderDirectory = "$PSScriptRoot\..\upstream-FSR3Unity\Packages\fidelityfx.fsr\Shaders",
    [string]$OutputDirectory = "$PSScriptRoot\..\ShaderProject\Assets\FSR3\Shaders"
)

$ErrorActionPreference = 'Stop'
$UpstreamShaderDirectory = (Resolve-Path $UpstreamShaderDirectory).Path

if (Test-Path $OutputDirectory) { Remove-Item $OutputDirectory -Recurse -Force }
New-Item -ItemType Directory -Force $OutputDirectory | Out-Null
$OutputDirectory = (Resolve-Path $OutputDirectory).Path

# --- 1. Copy shared include files (FSR3 upscaler + its dependencies only, no .meta files) -------------------
Copy-Item "$UpstreamShaderDirectory\ffx_fsr_unity_common.cginc" $OutputDirectory
New-Item -ItemType Directory -Force "$OutputDirectory\shaders" | Out-Null
Get-ChildItem "$UpstreamShaderDirectory\shaders" -File |
    Where-Object { $_.Extension -ne '.meta' -and $_.Name -notmatch '^ffx_fsr2_' } |
    ForEach-Object { Copy-Item $_.FullName "$OutputDirectory\shaders\" }
foreach ($subdirectory in 'fsr1', 'fsr3upscaler', 'spd') {
    New-Item -ItemType Directory -Force "$OutputDirectory\shaders\$subdirectory" | Out-Null
    Get-ChildItem "$UpstreamShaderDirectory\shaders\$subdirectory" -File |
        Where-Object Extension -ne '.meta' |
        ForEach-Object { Copy-Item $_.FullName "$OutputDirectory\shaders\$subdirectory\" }
}

# --- 2. Convert cbuffers in the FSR3 callbacks header to StructuredBuffers -----------------------------------
$callbacksPath = "$OutputDirectory\shaders\fsr3upscaler\ffx_fsr3upscaler_callbacks_hlsl.h"
$callbacksText = [IO.File]::ReadAllText($callbacksPath)

$cbufferPattern = '(?s)#if defined\((?<bindMacro>\w+)\)\s*\r?\ncbuffer\s+(?<bufferName>\w+)\s*:\s*FFX_FSR3UPSCALER_DECLARE_CB\(\w+\)\s*\{(?<fields>.*?)\};(?<rest>.*?)#endif // #if defined\(\k<bindMacro>\)'
$convertedCount = 0
$callbacksText = [regex]::Replace($callbacksText, $cbufferPattern, {
    param($match)
    $bindMacro = $match.Groups['bindMacro'].Value
    $bufferName = $match.Groups['bufferName'].Value
    $fieldsBlock = $match.Groups['fields'].Value
    $restOfBlock = $match.Groups['rest'].Value

    $fieldNames = [regex]::Matches($fieldsBlock, '^\s*\w+\s+(\w+)\s*;', 'Multiline') | ForEach-Object { $_.Groups[1].Value }
    $structName = "${bufferName}_${bindMacro}_Data"

    foreach ($fieldName in $fieldNames) {
        $restOfBlock = [regex]::Replace($restOfBlock, "return\s+$fieldName\s*;", "return ${bufferName}[0].$fieldName;")
    }
    # Size macro relied on sizeof(cbuffer); keep it meaningful for the struct
    $restOfBlock = $restOfBlock.Replace("sizeof($bufferName)", "sizeof($structName)")

    $script:convertedCount++
    "#if defined($bindMacro)`r`n// [ResoniteFSR3] cbuffer converted to StructuredBuffer for Unity 2019 compatibility`r`nstruct $structName`r`n{$fieldsBlock};`r`nStructuredBuffer<$structName> $bufferName;$restOfBlock#endif // #if defined($bindMacro)"
})
if ($convertedCount -ne 5) { throw "Expected to convert 5 cbuffers, converted $convertedCount" }
if ($callbacksText -match '(?m)^\s*cbuffer\s') { throw "A cbuffer declaration remains in the callbacks header" }
[IO.File]::WriteAllText($callbacksPath, $callbacksText)
Write-Host "Converted $convertedCount cbuffers to StructuredBuffers"

# The TCR auto-generate pass reads cbGenerateReactive fields directly instead of through getters; route them
# through the getters so they resolve to the StructuredBuffer.
$tcrPassPath = "$OutputDirectory\shaders\ffx_fsr3upscaler_tcr_autogen_pass.hlsl"
$tcrPassText = [IO.File]::ReadAllText($tcrPassPath)
$fieldToGetter = [ordered]@{ 'fReactiveScale' = 'ReactiveScale()'; 'fReactiveMax' = 'ReactiveMax()'; 'fTcScale' = 'TcScale()'; 'fTcThreshold' = 'TcThreshold()' }
foreach ($fieldName in $fieldToGetter.Keys) {
    $tcrPassText = [regex]::Replace($tcrPassText, "\b$fieldName\b", $fieldToGetter[$fieldName])
}
[IO.File]::WriteAllText($tcrPassPath, $tcrPassText)

# --- 3. Generate fixed-variant .compute files ----------------------------------------------------------------
# Resonite renderer: DX11 (reversed Z), motion vectors at render resolution, no texture arrays, FP32.
$header = @"
// Generated by tools/prepare-shaders.ps1 for ResoniteFSR3 (Unity 2019.4 backport of FSR3Unity by Nico de Poel, MIT).
// Keywords are fixed #defines because Unity 2019 does not support multi_compile in compute shaders.
#pragma kernel CS

"@

function New-ComputeVariant([string]$passName, [string]$variantSuffix, [string[]]$defines) {
    $upstreamCompute = [IO.File]::ReadAllText("$UpstreamShaderDirectory\ffx_fsr3upscaler_${passName}_pass.compute")
    $includeIndex = $upstreamCompute.IndexOf('#include "ffx_fsr_unity_common.cginc"')
    if ($includeIndex -lt 0) { throw "Include not found in $passName" }
    $body = $upstreamCompute.Substring($includeIndex)
    $defineLines = ($defines | ForEach-Object { "#define $_ 1" }) -join "`r`n"
    $fileName = "fsr3_${passName}${variantSuffix}.compute"
    [IO.File]::WriteAllText("$OutputDirectory\$fileName", "$header$defineLines`r`n`r`n$body")
    Write-Host "  $fileName  [$($defines -join ', ')]"
}

Write-Host "Generating compute variants:"
$lowResMotionVectors = 'FFX_FSR3UPSCALER_OPTION_LOW_RESOLUTION_MOTION_VECTORS'
foreach ($hdr in $false, $true) {
    foreach ($sharpen in $false, $true) {
        $defines = @($lowResMotionVectors)
        $suffix = ''
        if ($hdr) { $defines += 'FFX_FSR3UPSCALER_OPTION_HDR_COLOR_INPUT'; $suffix += '_hdr' }
        if ($sharpen) { $defines += 'FFX_FSR3UPSCALER_OPTION_APPLY_SHARPENING'; $suffix += '_sharpen' }
        New-ComputeVariant 'accumulate' $suffix $defines
    }
}
New-ComputeVariant 'prepare_inputs' '' @($lowResMotionVectors, 'FFX_FSR3UPSCALER_OPTION_INVERTED_DEPTH')
foreach ($passName in 'luma_pyramid', 'shading_change_pyramid', 'shading_change', 'prepare_reactivity', 'luma_instability', 'rcas', 'autogen_reactive', 'tcr_autogen', 'debug_view') {
    New-ComputeVariant $passName '' @()
}
